def get_credentials() -> tuple[str, str, str]:
    cf_account = os.environ.get("CF_ACCOUNT_ID", "").strip()
    access_key  = os.environ.get("AWS_ACCESS_KEY_ID", "").strip()
    secret_key  = os.environ.get("AWS_SECRET_ACCESS_KEY", "").strip()
    if not cf_account or not access_key:
        log.error("FATAL: CF_ACCOUNT_ID or AWS_ACCESS_KEY_ID not set. Skipping resync.")
        sys.exit(1)
    return cf_account, access_key, secret_key


def s3_cp(src: str, dst_bucket: str, dst_key: str, endpoint: str,
          cache_control: str = "no-cache, no-store, must-revalidate") -> bool:
    cmd = [
        "aws", "s3", "cp", src, f"s3://{dst_bucket}/{dst_key}",
        "--endpoint-url", endpoint,
        "--region", R2_S3_REGION,
        "--content-type", "application/json",
        "--cache-control", cache_control,
        "--only-show-errors",
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode == 0:
        log.info("OK: %s -> s3://%s/%s", src, dst_bucket, dst_key)
        return True
    log.warning(
        "WARN: Upload failed (%d): %s %s",
        result.returncode, result.stdout.strip()[:200], result.stderr.strip()[:200],
    )
    return False


def count_items(path: Path) -> int:
    """Return item count for a JSON file (array or dict with items/data/reports key)."""
    try:
        d = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(d, list):
            return len(d)
        for k in ("items", "data", "reports", "advisories"):
            if isinstance(d.get(k), list):
                return len(d[k])
    except Exception as exc:
        # v184.0: Log instead of silently swallowing — zero count returned but
        # the warning surfaces JSON parse errors or encoding issues in CI logs.
        log.warning("count_items(%s): parse error — %s (uploading anyway)", path.name, exc)
    return 0


# Public R2 latest.json must pass the exact Worker TLP/freshness contract.
# Validate the sanitized upload-only copy BEFORE any R2 PUT.
_WORKER_PUBLIC_FEED_CHECK = "scripts/p0_r2_public_feed_diagnostic.mjs"
_SAFE_REASONS = frozenset({
    "FEED_FRESHNESS_OR_STRUCTURE", "PUBLICATION_NODE_BUDGET",
    "TLP_BOUNDARY_REJECTION", "UNLABELED_OR_RESTRICTED_RECORDS",
    "UNLABELED_NESTED_ADVISORY", "NONE",
})


def assert_worker_deliverable_latest(latest_path: Path, parents=None) -> None:
    """Fail closed on rejected latest.json before any R2 write.

    This uses the existing Node diagnostic's Worker read boundary; it logs
    only safe error codes, never advisory bodies, identifiers or credentials.
    Post-upload live gateway parity still requires separate verification.
    """
    if not latest_path.is_file() or stale_manifest_reason(latest_path):
        raise ValueError("P0_PUBLIC_LATEST_NOT_REGENERATED")
    with tempfile.TemporaryDirectory(prefix="cdb-p0-latest-preflight-") as tmp:
        safe = tlp_safe_public_json_source(latest_path, Path(tmp),
                                           "api/v1/intel/latest.json", parents)
        if safe is None:
            raise ValueError("P0_PUBLIC_LATEST_TLP_SANITIZATION_DENIED")
        try:
            check = subprocess.run(
                ["node", str(REPO_ROOT / _WORKER_PUBLIC_FEED_CHECK), str(safe)],
                cwd=REPO_ROOT, capture_output=True, text=True, timeout=25,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise ValueError("P0_PUBLIC_LATEST_WORKER_PREFLIGHT_UNAVAILABLE") from exc
        try:
            report = json.loads(check.stdout)
            reason = report.get("root_cause_family")
            verified = (isinstance(report, dict) and check.returncode == 0
                        and report.get("verdict") == "DELIVERABLE"
                        and report.get("worker_public_tlp_gate") == "PASS"
                        and report.get("freshness") == "FRESH")
        except (ValueError, TypeError, AttributeError):
            reason, verified = None, False
        if not verified:
            reason = reason if reason in _SAFE_REASONS else "UNVERIFIED"
            raise ValueError("P0_PUBLIC_LATEST_WORKER_REJECTED:" + reason)


PAID_PRO_KEY = "api/v1/intel/latest_pro.json"
PAID_FINAL_SYNC_ENV = "CDB_FINAL_PAID_R2_SYNC"


def assert_final_paid_pro_pair(root: Path) -> None:
    """Offline, fail-closed FREE/PRO generation and TLP parity before any R2 PUT.

    Both publisher bundles are generated in one invocation. Never write an
    early, unknown-timestamp, empty, mismatched or TLP-modified PRO artifact.
    This check makes no network call and never modifies source files.
    """
    docs = {}
    for name in ("latest.json", "latest_pro.json"):
        path = root / "api" / "v1" / "intel" / name
        if not path.is_file():
            raise ValueError("P0_PAID_PARITY_MISSING_ARTIFACT")
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError, UnicodeError) as exc:
            raise ValueError("P0_PAID_PARITY_UNREADABLE_ARTIFACT") from exc
        if not isinstance(data, dict):
            raise ValueError("P0_PAID_PARITY_NOT_OBJECT")
        freshness = classify_manifest_freshness(data.get("generated_at"))
        if freshness["state"] != FRESH:
            raise ValueError("P0_PAID_PARITY_FRESHNESS_UNVERIFIED")
        items = data.get("items")
        if (not isinstance(items, list) or not items or
                type(data.get("count")) is not int or data["count"] != len(items)):
            raise ValueError("P0_PAID_PARITY_COUNT_UNVERIFIED")
        ids = [it.get("id") if isinstance(it, dict) else None for it in items]
        if any(not isinstance(ident, str) or not ident.strip() for ident in ids):
            raise ValueError("P0_PAID_PARITY_RECORD_ID_UNVERIFIED")
        if len(set(ids)) != len(ids):
            raise ValueError("P0_PAID_PARITY_DUPLICATE_RECORD")
        docs[name] = (data, ids)

    free, free_ids = docs["latest.json"]
    paid, paid_ids = docs["latest_pro.json"]
    if (free["generated_at"] != paid["generated_at"] or
            free_ids != paid_ids or paid.get("tier") != "PRO"):
        raise ValueError("P0_PAID_PARITY_SOURCE_DRIFT")

    # The last-mile TLP sanitizer must not silently remove or rewrite
    # paid source content. Producer-side TLP authorization must be explicit.
    from tlp_public_boundary import build_parent_index
    parents = build_parent_index([
        root / "api" / "feed.json",
        root / "data" / "feed_manifest.json",
        root / "data" / "stix" / "feed_manifest.json",
    ])
    with tempfile.TemporaryDirectory(prefix="cdb-pro-r2-parity-") as tmp:
        verified_path = tlp_safe_public_json_source(
            root / PAID_PRO_KEY, Path(tmp), PAID_PRO_KEY, parents)
        if verified_path is None:
            raise ValueError("P0_PAID_PARITY_TLP_UNVERIFIED")
        try:
            verified = json.loads(verified_path.read_text(encoding="utf-8"))
        except (OSError, ValueError, UnicodeError) as exc:
            raise ValueError("P0_PAID_PARITY_TLP_UNREADABLE") from exc
        if verified != paid:
            raise ValueError("P0_PAID_PARITY_TLP_MODIFIED")


def main() -> None:
    log.info("=" * 64)
    log.info("SENTINEL APEX v%s -- R2 Post-STAGE-3.93 Manifest Resync", PIPELINE_VERSION)
    log.info("ROOT CAUSE FIX: upload final post-generation manifests to R2")
    log.info("=" * 64)

    os.chdir(REPO_ROOT)

    final_paid_sync = os.environ.get(PAID_FINAL_SYNC_ENV) == "1"
    if final_paid_sync:
        try:
            assert_final_paid_pro_pair(REPO_ROOT)
        except ValueError as exc:
            # Fail BEFORE credentials and any PUT. No split-generation
            # paid manifests are permitted at the final publication point.
            log.critical("P0 final PRO publication refused: %s", exc)
            sys.exit(1)

    # Fail before first PUT if exact public manifest would cause API 503.
    _parents = build_parent_index([
        REPO_ROOT / "api" / "feed.json", REPO_ROOT / "data" / "feed_manifest.json",
        REPO_ROOT / "data" / "stix" / "feed_manifest.json",
    ])
    _latest_source = REPO_ROOT / "api/v1/intel/latest.json"
    if _latest_source.is_file() and not stale_manifest_reason(_latest_source):
        # Do not poison a previously healthy latest.json with a newly
        # generated document that the customer Worker will reject.
        try:
            assert_worker_deliverable_latest(_latest_source, _parents)
        except ValueError as exc:
            log.critical("P0 R2 RESYNC REFUSED BEFORE WRITES: %s", exc)
            sys.exit(1)
    else:
        # Existing Stage 4.1 fallback semantics: if generation failed or the
        # checkout has an old latest.json, do not upload that stale manifest.
        # Other independently guarded keys (notably api/feed.json) may still
        # be resynced. Never certify customer availability from this state.
        log.warning("P0 latest.json absent/stale: preserving existing per-key skip; no live-feed certification")

    cf_account, _, _ = get_credentials()
    endpoint = f"https://{cf_account}.r2.cloudflarestorage.com"

    uploaded = 0
    skipped  = 0
    failed   = 0
    # The final paid sync may not report success just because no PUT failed.
    # A missing/stale/withheld PRO artifact previously counted as SKIPPED
    # and Stage 4.1 exited 0, leaving customers with the prior paid bundle.
    paid_pro_uploaded = False

    _tlp_parents = build_parent_index([REPO_ROOT / "api" / "feed.json", REPO_ROOT / "data" / "feed_manifest.json",
                                       REPO_ROOT / "data" / "stix" / "feed_manifest.json"])
    for src_rel, dst_key, cache_ctrl in RESYNC_FILES:
        # Stage 3.93.6 remains FREE-only. Stage 4.1 explicitly enables the
        # one final PRO PUT, replacing (not adding to) Stage 3.5's early PUT.
        if dst_key == PAID_PRO_KEY and not final_paid_sync:
            continue
        src_path = REPO_ROOT / src_rel
        if not src_path.exists():
            log.warning("SKIP: %s not found -- STAGE 3.93 may not have generated it yet", src_rel)
            skipped += 1
            continue
        stale = stale_manifest_reason(src_path)
        if stale:
            # STAGE 4.1 runs even when the run failed before STAGE 3.93, in
            # which case these files are still the stale git checkout.
            # Uploading them would roll production back (run 35867879014).
            log.warning("SKIP (stale): %s -- %s", src_rel, stale)
            print(f"::warning::r2_resync: skipped stale {src_rel} ({stale})", flush=True)
            skipped += 1
            continue
        # P0 #725: api/feed.json is an anonymously served R2 object.
        # Re-synchronizing the original raw file would undo the TLP filtering
        # performed by the primary uploader in STAGE 3.5. Apply the identical
        # authority to fresh bytes here, without changing the source on disk.
        if dst_key == "api/feed.json":
            try:
                with tempfile.TemporaryDirectory(prefix="cdb-p0-tlp-resync-") as tmp:
                    safe_path = tlp_safe_public_feed_source(src_path, Path(tmp))
                    count = count_items(safe_path)
                    log.info("Uploading TLP-verified %s (%d items) -> R2 %s ...", src_rel, count, dst_key)
                    ok = s3_cp(str(safe_path), BUCKET_DATA, dst_key, endpoint, cache_ctrl)
            except (OSError, ValueError, TypeError) as exc:
                log.critical("P0 TLP verification refused R2 resync: %s", exc)
                sys.exit(1)  # no raw fallback, and api/feed.json is first in RESYNC_FILES
        elif dst_key.endswith(".json"):
            # P0 #721: same last-mile authority for every other JSON object in the final resync.
            with tempfile.TemporaryDirectory(prefix="cdb-p0-tlp-resync-") as tmp:
                safe_path = tlp_safe_public_json_source(src_path, Path(tmp), dst_key, _tlp_parents)
                if safe_path is None:
                    log.error("SKIP: %s cannot be verified for TLP publication; withheld from R2", src_rel)
                    skipped += 1
                    continue
                count = count_items(safe_path)
                log.info("Uploading TLP-verified %s (%d items) -> R2 %s ...", src_rel, count, dst_key)
                ok = s3_cp(str(safe_path), BUCKET_DATA, dst_key, endpoint, cache_ctrl)
        else:
            count = count_items(src_path)
            log.info("Uploading %s (%d items) -> R2 %s ...", src_rel, count, dst_key)
            ok = s3_cp(str(src_path), BUCKET_DATA, dst_key, endpoint, cache_ctrl)
        if ok:
            uploaded += 1
            if final_paid_sync and dst_key == PAID_PRO_KEY:
                paid_pro_uploaded = True
        else:
            failed += 1

    if final_paid_sync and not paid_pro_uploaded:
        # A successful final stage is proof of a real accepted PRO PUT, not
        # merely a clean local preflight or no exception from the uploader.
        # Keep earlier per-key skip/deny behavior unchanged for FREE-only
        # Stage 3.93.6 and fail the mandatory paid Stage 4.1.
        log.critical("P0_FINAL_PRO_UPLOAD_NOT_CONFIRMED: denying production release")
        sys.exit(1)

    log.info("")
    log.info("R2 resync complete: %d uploaded, %d skipped, %d failed.", uploaded, skipped, failed)

    # Feed item count summary for CI visibility
    feed_path = REPO_ROOT / "api" / "feed.json"
    if feed_path.exists():
        total = count_items(feed_path)
        log.info("api/feed.json: %d items now live in R2 (dashboard will show fresh data).", total)

    if failed > 0:
        log.warning(
            "WARN: %d file(s) failed to upload to R2. "
            "Worker will fall back to KV/GitHub for those endpoints.",
            failed,
        )
        # v184.0 P1 FIX: Emit GitHub Actions error annotation so the failure is
        # VISIBLE in the workflow run UI even though we do not block the pipeline.
        # Callers (Stage 3.93.6, Stage 4.1) wrap this in an if/else block that
        # catches exit(1) and emits a ::warning:: annotation, always exiting 0.
        print(
            f"::error::R2 resync: {failed} file(s) failed to upload to R2. "
            "Feed may be stale. Verify CF_ACCOUNT_ID, CF_R2_ACCESS_KEY_ID, "
            "CF_R2_SECRET_ACCESS_KEY secrets and bucket 'sentinel-apex-data' policy.",
            flush=True,
        )
        sys.exit(1)  # Non-zero so callers can detect and surface the failure

    log.info("All post-STAGE-3.93 manifests successfully synced to R2.")
    print(
        f"::notice::R2 resync: {uploaded} files uploaded, {skipped} skipped. Feed is fresh.",
        flush=True,
    )
    sys.exit(0)


def handle_unexpected_main_error(exc: Exception) -> None:
    """Preserve legacy free-only behavior; final paid sync always fails closed.

    Avoid printing arbitrary exception messages in paid mode: SDK exceptions
    sometimes contain request headers/URLs or private endpoint information.
    """
    if os.environ.get(PAID_FINAL_SYNC_ENV) == "1":
        log.critical("P0_FINAL_PRO_SYNC_UNEXPECTED_EXCEPTION: %s", type(exc).__name__)
        print("::error::P0 final paid PRO R2 sync failed unexpectedly; NO-GO", flush=True)
        raise SystemExit(1)
    import traceback
    log.warning("r2_resync_manifests.py unhandled error (non-fatal): %s\n%s",
                exc, traceback.format_exc())
    print(f"::warning::r2_resync_manifests.py unexpected error: {exc}. "
          "R2 may not have the latest data. Check runner logs.", flush=True)
    raise SystemExit(0)


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception as exc:
        handle_unexpected_main_error(exc)
